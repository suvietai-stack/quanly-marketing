-- Role V2 entries only, positions exclusively attached to enabled blocks.
WITH RECURSIVE tree AS (
 SELECT id,parent_id,id AS block_id,ARRAY[id] path FROM public.org_units
 WHERE kind='block' AND active AND id=ANY(ARRAY['biz-block','showroom-block','b5e00000-0000-4000-8000-000000000002'])
 UNION ALL SELECT u.id,u.parent_id,t.block_id,t.path||u.id
 FROM tree t JOIN public.org_units u ON u.parent_id=t.id
 WHERE u.active AND NOT u.id=ANY(t.path)
), eligible AS (
 SELECT DISTINCT pr.role_id,t.kind
 FROM public.org_position_roles pr
 JOIN public.org_titles t ON t.id=pr.title_id AND t.active
 JOIN tree tr ON tr.id=pr.unit_id
), grants AS (
 SELECT role_id,BOOL_OR(kind='manager') is_manager FROM eligible GROUP BY role_id
)
UPDATE public.app_roles r SET
 permissions=(SELECT array_agg(DISTINCT x ORDER BY x)
              FROM unnest(r.permissions||CASE WHEN grants.is_manager
               THEN ARRAY['k3hub.use','k3hub.center','k3.use']
               ELSE ARRAY['k3hub.use','k3.use'] END) AS x),
 updated_at=now()
FROM grants WHERE r.id=grants.role_id AND r.role_kind='position' AND r.catalog_generation=2;

UPDATE public.app_roles r SET
 permissions=(SELECT array_agg(DISTINCT x ORDER BY x) FROM
   unnest(r.permissions||ARRAY['k3hub.use','k3hub.center']) x), updated_at=now()
WHERE r.id='role-v2-executive' AND r.role_kind='position' AND r.catalog_generation=2;

-- Consistent, cycle-safe org path resolution; never infer access from names.
CREATE OR REPLACE FUNCTION private.k3hub_path(_unit text)
RETURNS TABLE(id text,kind text,depth int)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path=public AS $fn$
 WITH RECURSIVE a AS (
  SELECT u.id,u.parent_id,u.kind,0 depth,ARRAY[u.id] path FROM public.org_units u WHERE u.id=_unit AND u.active
  UNION ALL SELECT u.id,u.parent_id,u.kind,a.depth+1,a.path||u.id
  FROM a JOIN public.org_units u ON u.id=a.parent_id AND u.active
  WHERE a.depth<32 AND NOT u.id=ANY(a.path)
 ) SELECT a.id,a.kind,a.depth FROM a
$fn$;

CREATE OR REPLACE FUNCTION private.k3hub_policy_at(_date date)
RETURNS text[] LANGUAGE sql STABLE SECURITY DEFINER SET search_path=public AS $fn$
 SELECT coalesce((SELECT applied_block_ids FROM public.k3hub_policy_versions
  WHERE effective_from<=_date ORDER BY effective_from DESC,revision DESC LIMIT 1),'{}'::text[])
$fn$;

CREATE OR REPLACE FUNCTION private.k3hub_is_enabled(_unit text,_date date)
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path=public AS $fn$
 SELECT EXISTS(SELECT 1 FROM private.k3hub_path(_unit) p
 WHERE p.kind='block' AND p.id=ANY(private.k3hub_policy_at(_date)))
$fn$;

CREATE OR REPLACE FUNCTION private.k3hub_exec(_actor uuid)
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path=public AS $fn$
 SELECT private.is_super_admin(_actor) OR (
 private.has_permission(_actor,'k3hub.center')
 AND NOT private.k3_personal_denied(_actor,'k3.view_scope')
 AND EXISTS(
  SELECT 1 FROM public.org_assignments a
  JOIN public.org_position_roles pr ON pr.unit_id=a.unit_id AND pr.title_id=a.title_id
  WHERE a.user_id=_actor AND a.status='active' AND a.unit_id='org-company'
   AND a.starts_at<=now() AND (a.ends_at IS NULL OR a.ends_at>now())
   AND pr.role_id='role-v2-executive'
 ))
$fn$;

CREATE OR REPLACE FUNCTION private.k3hub_can_view(_actor uuid,_target uuid,_unit text,_date date)
RETURNS boolean LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path=public AS $fn$
DECLARE membership boolean;
BEGIN
 IF NOT private.is_active(_actor) OR NOT private.is_active(_target)
  OR NOT private.k3hub_is_enabled(_unit,_date) THEN RETURN false; END IF;
 SELECT EXISTS(
  SELECT 1 FROM public.org_assignments a WHERE a.user_id=_target AND a.status='active'
    AND a.starts_at<=now() AND (a.ends_at IS NULL OR a.ends_at>now())
    AND EXISTS(SELECT 1 FROM private.k3hub_path(a.unit_id) p WHERE p.id=_unit)
 ) INTO membership;
 IF NOT membership THEN RETURN false; END IF;
 IF _actor=_target THEN RETURN public.k3_can(_actor,'k3.use')
  AND (private.is_super_admin(_actor) OR private.has_permission(_actor,'k3hub.use')); END IF;
 IF private.k3hub_exec(_actor) THEN RETURN true; END IF;
 IF NOT private.has_permission(_actor,'k3hub.center')
  OR private.k3_personal_denied(_actor,'k3.view_scope') THEN RETURN false; END IF;
 RETURN EXISTS (
  SELECT 1 FROM public.org_assignments a
  JOIN public.org_titles t ON t.id=a.title_id AND t.kind='manager' AND t.active
  JOIN public.org_position_roles pr ON pr.unit_id=a.unit_id AND pr.title_id=a.title_id
  WHERE a.user_id=_actor AND a.status='active'
   AND a.starts_at<=now() AND (a.ends_at IS NULL OR a.ends_at>now())
   AND EXISTS(SELECT 1 FROM private.k3hub_path(_unit) p WHERE p.id=a.unit_id)
 );
END $fn$;

-- Current employee scopes and current organization rights. Day's historical
-- K3 entities must match the scoped org unit: no cross-unit goal/KPI exposure.
CREATE OR REPLACE FUNCTION public.k3hub_read(_date date,_unit text DEFAULT 'org-company')
RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path=public AS $fn$
DECLARE uid uuid:=auth.uid(); allowed_blocks text[]; response jsonb;
BEGIN
 IF uid IS NULL OR NOT private.is_active(uid) THEN RAISE EXCEPTION 'Cần đăng nhập.' USING ERRCODE='42501'; END IF;
 IF _date IS NULL OR _date<DATE '2020-01-01'
    OR _date>(now() AT TIME ZONE 'Asia/Ho_Chi_Minh')::date+31 THEN
    RAISE EXCEPTION 'Ngày xem không hợp lệ.'; END IF;
 IF _unit<>'org-company' AND NOT EXISTS(SELECT 1 FROM public.org_units WHERE id=_unit AND active)
 THEN RAISE EXCEPTION 'Không tìm thấy đơn vị.'; END IF;
 IF _unit='org-company' AND NOT private.k3hub_exec(uid) THEN
  RAISE EXCEPTION 'Trung tâm 3K toàn công ty chỉ dành cho điều hành.' USING ERRCODE='42501'; END IF;
 IF _unit<>'org-company' AND NOT private.k3hub_is_enabled(_unit,_date) THEN
  RAISE EXCEPTION 'Khối này chưa áp dụng 3K trong kỳ.' USING ERRCODE='42501'; END IF;

 SELECT jsonb_build_object(
   'date',_date,'unit_id',_unit,'server_now',now(),
   'can_config',private.is_super_admin(uid) OR private.has_permission(uid,'k3hub.config'),
   'blocks',coalesce((SELECT jsonb_agg(jsonb_build_object('id',u.id,'name',u.name,
       'enabled',u.id=ANY(private.k3hub_policy_at(_date))) ORDER BY u.name)
     FROM public.org_units u WHERE u.kind='block' AND u.active),'[]'::jsonb),
   'people',coalesce((SELECT jsonb_agg(to_jsonb(v) ORDER BY v.block_name,v.unit_name,v.full_name)
     FROM (
       SELECT DISTINCT ON (a.user_id,a.unit_id)
        a.user_id::text user_id,p.full_name,a.unit_id unit_id,u.name unit_name,
        b.id block_id,b.name block_name,t.name position,
        coalesce((
         SELECT count(*) FROM public.k3_goals g
         WHERE g.user_id=a.user_id AND g.deleted_at IS NULL
           AND g.period_start<=_date AND g.period_end>=_date
           AND (g.org_unit_id=a.unit_id OR
             (g.org_unit_id IS NULL AND g.department_id::text=a.unit_id))
        ),0)::int goals_count,
        coalesce((
         SELECT count(*) FROM public.k3_actions x
         JOIN public.k3_goals g ON g.id=x.goal_id AND g.deleted_at IS NULL
         WHERE x.assignee_id=a.user_id AND x.deleted_at IS NULL
          AND coalesce(x.start_date,g.period_start)<=_date
          AND coalesce(x.due_date,g.period_end)>=_date
          AND (g.org_unit_id=a.unit_id OR
             (g.org_unit_id IS NULL AND g.department_id::text=a.unit_id))
        ),0)::int actions_count,
        coalesce((
         SELECT count(*) FROM public.k3_kpi_results x
         JOIN public.k3_kpis k ON k.id=x.kpi_id
         JOIN public.k3_actions act ON act.id=k.action_id
         JOIN public.k3_goals g ON g.id=act.goal_id
         WHERE x.user_id=a.user_id AND x.work_date=_date
          AND x.deleted_at IS NULL AND x.review_reason IS NULL
          AND (g.org_unit_id=a.unit_id OR
             (g.org_unit_id IS NULL AND g.department_id::text=a.unit_id))
        ),0)::int results_count,
        CASE WHEN EXISTS(
          SELECT 1 FROM public.k3_employee_reviews er
          JOIN public.k3_days d ON d.user_id=er.user_id AND d.work_date=er.work_date
          WHERE er.user_id=a.user_id AND er.work_date=_date
           AND (d.org_unit_id=a.unit_id OR (d.org_unit_id IS NULL AND d.department_id::text=a.unit_id))
         ) THEN 'confirmed'
         WHEN EXISTS(
          SELECT 1 FROM public.k3_kpi_results r
          JOIN public.k3_kpis k ON k.id=r.kpi_id
          JOIN public.k3_actions act ON act.id=k.action_id
          JOIN public.k3_goals g ON g.id=act.goal_id
          WHERE r.user_id=a.user_id AND r.work_date=_date
           AND r.deleted_at IS NULL AND r.review_reason IS NULL
           AND (g.org_unit_id=a.unit_id OR (g.org_unit_id IS NULL AND g.department_id::text=a.unit_id))
         ) THEN 'updated'
         WHEN EXISTS(
          SELECT 1 FROM public.k3_goals g
          WHERE g.user_id=a.user_id AND g.deleted_at IS NULL AND g.period_start<=_date
           AND g.period_end>=_date
           AND (g.org_unit_id=a.unit_id OR (g.org_unit_id IS NULL AND g.department_id::text=a.unit_id))
         ) THEN 'planned'
         ELSE 'none' END AS state
       FROM public.org_assignments a
       JOIN public.profiles p ON p.id=a.user_id AND p.status='Đang hoạt động'
       JOIN public.org_units u ON u.id=a.unit_id AND u.active
       JOIN public.org_titles t ON t.id=a.title_id AND t.active
       JOIN LATERAL (
         SELECT root.id, root.name FROM private.k3hub_path(a.unit_id) pp
         JOIN public.org_units root ON root.id=pp.id AND root.kind='block'
         WHERE pp.id=ANY(private.k3hub_policy_at(_date)) ORDER BY pp.depth LIMIT 1
       ) b ON true
       WHERE a.status='active' AND a.starts_at<=now()
         AND (a.ends_at IS NULL OR a.ends_at>now())
         AND (_unit='org-company' OR EXISTS(
           SELECT 1 FROM private.k3hub_path(a.unit_id) pp WHERE pp.id=_unit))
         AND private.k3hub_can_view(uid,a.user_id,a.unit_id,_date)
       ORDER BY a.user_id,a.unit_id,t.kind DESC,t.name
     ) v),'[]'::jsonb)
  ) INTO response;
 RETURN response;
END $fn$;

CREATE OR REPLACE FUNCTION public.k3hub_policy_read()
RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path=public AS $fn$
DECLARE uid uuid:=auth.uid(); policy public.k3hub_policy_versions;
BEGIN
 IF NOT private.is_active(uid) OR NOT
   (private.is_super_admin(uid) OR private.has_permission(uid,'k3hub.config'))
 THEN RAISE EXCEPTION 'Không có quyền cấu hình 3K.' USING ERRCODE='42501'; END IF;
 SELECT * INTO policy FROM public.k3hub_policy_versions
 ORDER BY effective_from DESC,revision DESC LIMIT 1;
 RETURN jsonb_build_object('revision',policy.revision,'effective_from',policy.effective_from,
  'applied_block_ids',policy.applied_block_ids,'include_unassigned',policy.include_unassigned,
  'blocks',coalesce((SELECT jsonb_agg(jsonb_build_object('id',id,'name',name) ORDER BY name)
   FROM public.org_units WHERE active AND kind='block'),'[]'::jsonb),
  'today',(now() AT TIME ZONE 'Asia/Ho_Chi_Minh')::date);
END $fn$;

CREATE OR REPLACE FUNCTION public.k3hub_policy_save(_revision bigint,_date date,_blocks text[],_reason text)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $fn$
DECLARE uid uuid:=auth.uid(); last_ public.k3hub_policy_versions; ids text[];
BEGIN
 IF NOT private.is_active(uid) OR NOT
   (private.is_super_admin(uid) OR private.has_permission(uid,'k3hub.config'))
 THEN RAISE EXCEPTION 'Không có quyền cấu hình 3K.' USING ERRCODE='42501'; END IF;
 PERFORM pg_advisory_xact_lock(hashtext('k3hub_policy'),0);
 SELECT * INTO last_ FROM public.k3hub_policy_versions ORDER BY revision DESC LIMIT 1;
 IF _revision IS DISTINCT FROM last_.revision THEN RAISE EXCEPTION 'Cấu hình đã đổi, cần tải lại.' USING ERRCODE='40001'; END IF;
 IF _date<(now() AT TIME ZONE 'Asia/Ho_Chi_Minh')::date OR _date IS NULL
   OR (_date<last_.effective_from) THEN RAISE EXCEPTION 'Ngày hiệu lực không thể lùi về quá khứ.'; END IF;
 IF length(btrim(coalesce(_reason,'')))<5 THEN RAISE EXCEPTION 'Cần nhập lý do ít nhất 5 ký tự.'; END IF;
 SELECT coalesce(array_agg(DISTINCT x ORDER BY x),'{}') INTO ids FROM unnest(coalesce(_blocks,'{}')) AS x;
 IF EXISTS(SELECT 1 FROM unnest(ids) x
   WHERE NOT EXISTS(SELECT 1 FROM public.org_units WHERE id=x AND active AND kind='block'))
 THEN RAISE EXCEPTION 'Danh sách khối không hợp lệ.'; END IF;
 INSERT INTO public.k3hub_policy_versions(effective_from,applied_block_ids,reason,actor_id)
 VALUES(_date,ids,btrim(_reason),uid);
 RETURN public.k3hub_policy_read();
END $fn$;

