-- This trigger only records *explicit* V2 grants by a real Super Admin.
-- A stored dormant permission remains inactive; merely opening/saving a Role
-- without a diff never activates it. Remove, save, re-add, save = activate.
CREATE OR REPLACE FUNCTION private.track_role_permission_reactivation()
 RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER
 SET search_path TO 'public','private'
AS $function$
DECLARE actor uuid;
BEGIN
 IF TG_OP='DELETE' THEN
   DELETE FROM private.role_permission_reactivation WHERE role_id=OLD.id;
   RETURN OLD;
 END IF;
 IF TG_OP='INSERT' THEN
   DELETE FROM private.role_permission_reactivation WHERE role_id=NEW.id;
   RETURN NEW;
 END IF;
 IF NEW.permissions IS NOT DISTINCT FROM OLD.permissions THEN RETURN NEW; END IF;
 DELETE FROM private.role_permission_reactivation a
 WHERE a.role_id=NEW.id AND NOT (a.permission=ANY(NEW.permissions));
 actor:=auth.uid();
 IF NEW.catalog_generation=2 AND NOT NEW.is_system
    AND actor IS NOT NULL AND private.is_super_admin(actor) THEN
   INSERT INTO private.role_permission_reactivation(role_id,permission,actor_id)
   SELECT NEW.id,k,actor FROM unnest(NEW.permissions) k
   JOIN private.role_permission_initial_dormant f ON f.role_id=NEW.id AND f.permission=k
   WHERE NOT (k=ANY(OLD.permissions))
   ON CONFLICT(role_id,permission) DO UPDATE
     SET actor_id=EXCLUDED.actor_id,activated_at=clock_timestamp();
 END IF;
 RETURN NEW;
END;
$function$;
CREATE TRIGGER app_roles_track_permission_reactivation
 AFTER INSERT OR UPDATE OF permissions OR DELETE ON public.app_roles
 FOR EACH ROW EXECUTE FUNCTION private.track_role_permission_reactivation();

DO $post$
BEGIN
 IF (SELECT count(*) FROM private.role_permission_initial_dormant)<>930
    OR (SELECT count(*) FROM private.role_permission_reactivation)<>0
    OR NOT private.universal_dormant_fence('role-v2-sales-head','settings.view')
 THEN RAISE EXCEPTION 'STOP: dormant permissions unexpectedly activated'; END IF;
END;
$post$;
REVOKE ALL ON FUNCTION private.track_role_permission_reactivation() FROM PUBLIC;
COMMIT;
